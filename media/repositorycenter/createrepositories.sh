#!/usr/bin/env bash
set -Eeuo pipefail

# Create the 500 public PlanetBintang repositories from the central name catalog.
# Requires GitHub CLI (gh) and an authenticated account with permission to create
# repositories under the planetbintang owner.
OWNER="planetbintang"
LOG_FILE="repositorycreation.log"

if ! command -v gh >/dev/null 2>&1; then
  echo "GitHub CLI (gh) is required. Install it from https://cli.github.com/" >&2
  exit 1
fi
if ! gh auth status >/dev/null 2>&1; then
  echo "Authenticate first with: gh auth login" >&2
  exit 1
fi

created=0
skipped=0
failed=0

create_repo() {
  local name="$1"
  local full="${OWNER}/${name}"
  if gh repo view "$full" >/dev/null 2>&1; then
    printf 'SKIP existing %s\n' "$full" | tee -a "$LOG_FILE"
    skipped=$((skipped + 1))
    return 0
  fi

  if gh repo create "$full" --public --add-readme --description "PlanetBintang integrated desktop application module"; then
    printf 'CREATED public %s\n' "$full" | tee -a "$LOG_FILE"
    created=$((created + 1))
  else
    printf 'FAILED %s\n' "$full" | tee -a "$LOG_FILE"
    failed=$((failed + 1))
  fi
  sleep 2
}

